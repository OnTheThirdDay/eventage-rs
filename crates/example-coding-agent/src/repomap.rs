    #[test]
    fn an_enormous_workspace_degrades_to_directories_not_to_silence() {
        // Past the point where even bare paths fit, the map must stay
        // complete at *some* level rather than become a partial file list.
        let mut files: Vec<(String, String)> = Vec::new();
        for d in 0..40 {
            for f in 0..40 {
                files.push((
                    format!("area{d}/component{f}/implementation_module.rs"),
                    "pub fn work() {}\n".into(),
                ));
            }
        }
        let refs: Vec<(&str, &str)> = files
            .iter()
            .map(|(p, b)| (p.as_str(), b.as_str()))
            .collect();
        let dir = workspace(&refs);

        let map = build(dir.path(), 300);
        assert!(map.contains("too large to list file by file"), "{map}");
        // And it must not inherit the promise it cannot keep.
        assert!(!map.contains("if a path is not here"), "{map}");
        assert!(map.contains("do not read a file's absence"), "{map}");
        assert!(map.contains("`area0/component0/` — 1 files"), "{map}");
        // Every directory still accounted for.
        for d in [0, 17, 39] {
            assert!(map.contains(&format!("area{d}/")), "area{d} missing");
        }
    }

