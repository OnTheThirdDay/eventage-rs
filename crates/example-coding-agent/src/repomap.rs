    #[test]
    fn no_file_is_ever_dropped_to_save_space() {
        // The bug this shape exists to prevent: `src/llm/content.rs` was cut
        // under a budget, and an agent that read the map concluded the
        // multimodal support defined in it did not exist. Detail is
        // negotiable; the existence of a file is not.
        let mut files: Vec<(String, String)> = Vec::new();
        for i in 0..60 {
            files.push((
                format!("src/mod{i}.rs"),
                (0..20)
                    .map(|j| format!("pub fn a_fairly_long_symbol_name_{i}_{j}() {{}}\n"))
                    .collect(),
            ));
        }
        let refs: Vec<(&str, &str)> = files
            .iter()
            .map(|(p, b)| (p.as_str(), b.as_str()))
            .collect();
        let dir = workspace(&refs);

        // A budget far too small for the symbols, ample for the paths.
        let map = build(dir.path(), 400);
        for i in 0..60 {
            assert!(
                map.contains(&format!("mod{i}.rs")),
                "mod{i}.rs vanished:\n{map}"
            );
        }
        // And it spent what it had on detail for the best-ranked files.
        assert!(map.contains("a_fairly_long_symbol_name"), "{map}");
    }

